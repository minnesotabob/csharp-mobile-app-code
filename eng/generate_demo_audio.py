"""Original deterministic timing fixtures; no sampled recordings or third-party media."""
from pathlib import Path
import hashlib, json, math, struct, wave
root=Path(__file__).resolve().parents[1]
out=root/'src/GnazzosWorld.App/Resources/Raw';out.mkdir(parents=True,exist_ok=True)
records=[]
for name,seconds,frequency in [('demo_chimes.wav',10,440),('demo_pulses.wav',14,660),('background_timing.wav',60,880)]:
    samples=[];rate=8000
    for i in range(rate*seconds):
        t=i/rate;phase=t%2
        # A quiet 60ms, tapered sine every two seconds; silence otherwise.
        envelope=math.sin(math.pi*phase/.06)**2 if phase < .06 else 0
        samples.append(struct.pack('<h',round(3800*envelope*math.sin(2*math.pi*frequency*t))))
    with wave.open(str(out/name),'wb') as wav:
        wav.setnchannels(1);wav.setsampwidth(2);wav.setframerate(rate);wav.writeframes(b''.join(samples))
    data=(out/name).read_bytes();records.append({'file':name,'seconds':seconds,'sample_rate':rate,'channels':1,'bits':16,'sha256':hashlib.sha256(data).hexdigest()})
(root/'samples'/'audio-fixtures.json').write_text(json.dumps({'schema':1,'provenance':'Original mathematical timing signals, not music or podcast recordings. Generated by eng/generate_demo_audio.py. May be redistributed with the companion teaching sample.','files':records},indent=2)+'\n')
print(json.dumps(records))
