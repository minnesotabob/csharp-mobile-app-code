"""Original exact PNG test fixtures; synthetic metadata, no user photographs."""
from pathlib import Path
import base64, binascii, hashlib, json, struct, zlib
root=Path(__file__).resolve().parents[1]
def chunk(kind,data):
    return struct.pack('>I',len(data))+kind+data+struct.pack('>I',binascii.crc32(kind+data)&0xffffffff)
header=chunk(b'IHDR',struct.pack('>IIBBBBB',4,3,8,6,0,0,0))
pixels=b''.join(b'\0'+b''.join(bytes([x*60,y*80,120,255]) for x in range(4)) for y in range(3))
encoded=chunk(b'IDAT',zlib.compress(pixels))+chunk(b'IEND',b'')
records=[]
for name,extra in [('clean',b''),('synthetic-metadata',chunk(b'tEXt',b'Author\0Synthetic reference only')+chunk(b'eXIf',b'SYNTHETIC EXIF TEST MARKER'))]:
    data=b'\x89PNG\r\n\x1a\n'+header+extra+encoded
    records.append({'name':name,'width':4,'height':3,'sha256':hashlib.sha256(data).hexdigest(),'base64':base64.b64encode(data).decode()})
(root/'samples'/'attachment-fixtures.json').write_text(json.dumps({'schema':1,'provenance':'Original mathematical 4x3 RGBA PNGs generated by eng/generate_attachment_fixtures.py. Metadata is synthetic, not a user location or photograph.','files':records},indent=2)+'\n')
print('Generated two original exact PNG fixtures')
